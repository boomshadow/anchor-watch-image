#!/usr/bin/env bash
# Tests tools/gen-index in throwaway repos: fresh/stale detection, rewrite,
# validation errors, and usage.
set -euo pipefail

here=$(cd "$(dirname "$0")/.." && pwd)
tool="$here/tools/gen-index"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

fails=0
expect() { # expect <name> <want exit> <cmd...>
    local name=$1 want=$2; shift 2
    set +e
    (cd "$repo" && "$@") >"$tmp/out" 2>&1
    local got=$?
    set -e
    if [ "$got" = "$want" ]; then echo "ok   $name (exit $got)"
    else echo "FAIL $name: exit $got (want $want)"; sed 's/^/     /' "$tmp/out"; fails=$((fails + 1)); fi
}
fixture() {
    repo=$(mktemp -d -p "$tmp"); git -C "$repo" init -q -b main
    mkdir -p "$repo/docs/specs" "$repo/docs/decisions"
    adr ADR-001-choice.md "## Context\n\n## Decision\n\n## Consequences"
}
adr() { # adr <file> <body>
    printf -- '---\ntitle: "Choice"\ndescription: "d"\nstatus: accepted\ntags: [x]\n---\n%b\n' "$2" > "$repo/docs/decisions/$1"
}
spec() { # spec <file> <status> [tags-line]
    cat > "$repo/docs/specs/$1" <<DOC
---
title: "A \"quoted\" title"
description: "Does | something"
status: $2
tags: ${3:-[a, 'b']}
---
body
DOC
}

fixture
spec SPEC-001-thing.md accepted
expect "stale indexes"                1 "$tool" --check
expect "rewrite"                      0 "$tool"
expect "fresh after rewrite"          0 "$tool" --check
grep -q '^# Specifications$' "$repo/docs/specs/INDEX.md" || { echo "FAIL heading"; fails=$((fails+1)); }
grep -q '^# Architecture Decision Records$' "$repo/docs/decisions/INDEX.md" || { echo "FAIL ADR heading"; fails=$((fails+1)); }
grep -q 'A "quoted" title' "$repo/docs/specs/INDEX.md" || { echo "FAIL unquote"; fails=$((fails+1)); }
grep -q 'Does \\| something' "$repo/docs/specs/INDEX.md" || { echo "FAIL pipe escape"; fails=$((fails+1)); }
grep -q '| a, b |' "$repo/docs/specs/INDEX.md" || { echo "FAIL tags"; fails=$((fails+1)); }
sed -i '1s/.*/<!-- AUTO-GENERATED by another tool -->/' "$repo/docs/specs/INDEX.md"
expect "check ignores header comment" 0 "$tool" --check
echo hand-edit >> "$repo/docs/specs/INDEX.md"
expect "hand-edited index is stale"   1 "$tool" --check
expect "help"                         0 "$tool" --help
expect "bad usage"                    2 "$tool" --bogus
expect "outside a repo"               2 bash -c "cd / && '$tool' --check"

fixture; spec SPEC-001-thing.md published
expect "invalid status"               2 "$tool"
fixture; spec SPEC-001-thing.md accepted; spec SPEC-001-other.md accepted
expect "reused number"                2 "$tool"
fixture; spec SPEC-1-thing.md accepted
expect "bad file name"                2 "$tool"
fixture; spec SPEC-001-thing.md accepted '(a, b)'
expect "tags not a list"              2 "$tool"
fixture; rm "$repo/docs/decisions/ADR-001-choice.md"; spec SPEC-001-thing.md accepted
expect "empty ADR dir, header-only"   0 "$tool"
expect "header-only index is fresh"   0 "$tool" --check
rewritten=$(cat "$repo/docs/specs/INDEX.md"); sed -i '1s/.*/<!-- AUTO-GENERATED by other -->/' "$repo/docs/specs/INDEX.md"
(cd "$repo" && "$tool" >/dev/null); head -1 "$repo/docs/specs/INDEX.md" | grep -q "AUTO-GENERATED by other" || { echo "FAIL write keeps foreign header"; fails=$((fails+1)); }
for bad in "title: Foo: Bar" "title: 0x1F" "title: 1:30" "title: .inf" "title: [a]" "title: &a Foo" "title: !!str Foo" "title: @x" "title: %x" "title: Choice # note" "title: yes" "title: 'it''s'" 'title: "a\tb"' "title: 'open"; do
    fixture; printf -- '---\n%s\ndescription: "d"\nstatus: accepted\ntags: [x]\n---\nb\n' "$bad" > "$repo/docs/specs/SPEC-001-t.md"
    expect "rejects: $bad"              2 "$tool"
done
fixture; spec SPEC-001-thing.md accepted; adr ADR-001-choice.md "## Context"
expect "ADR missing sections"         2 "$tool"
fixture; spec SPEC-001-thing.md accepted; adr ADR-001-choice.md "# Title\n## Context\n## Decision\n## Consequences"
sed -i 's/$/\r/' "$repo/docs/decisions/ADR-001-choice.md"
expect "CRLF frontmatter"             0 "$tool"
fixture; spec SPEC-001-thing.md draft
expect "draft status rejected"        2 "$tool"
fixture; spec SPEC-001-thing.md accepted '[Mixed]'
expect "uppercase tag rejected"       2 "$tool"
fixture; printf -- '---\ntitle: "T"\ndescription: "wrapped over\n  several lines, as in\n  the SPEC-000 template"\nstatus: accepted\ntags: [x]\n---\nb\n' > "$repo/docs/specs/SPEC-001-t.md"
expect "folded quoted description"     0 "$tool"
grep -q 'wrapped over several lines, as in the SPEC-000 template' "$repo/docs/specs/INDEX.md" || { echo "FAIL fold"; fails=$((fails+1)); }
fixture; printf -- '---\ntitle:\ndescription: "d"\nstatus: accepted\ntags: [x]\n---\nb\n' > "$repo/docs/specs/SPEC-001-t.md"
msg=$(cd "$repo" && "$tool" 2>&1 || true); case "$msg" in *"missing frontmatter field"*) ;; *) echo "FAIL empty value message"; fails=$((fails+1)) ;; esac
fixture; spec SPEC-001-thing.md accepted; printf -- '---\ntitle: "T"\ndescription: "d"\nstatus: accepted\ntags: [x]\n---' > "$repo/docs/specs/SPEC-002-eof.md"
expect "closing --- at end of file"   0 "$tool"
fixture; spec SPEC-001-thing.md accepted; mkdir "$repo/docs/specs/INDEX.md"
expect "INDEX.md is a directory"      2 "$tool" --check
fixture; printf 'no frontmatter\n' > "$repo/docs/specs/SPEC-001-thing.md"
expect "missing frontmatter"          2 "$tool"

# --check reads the pushed commit (PRE_COMMIT_TO_REF or --ref), not the working tree.
commit() { git -C "$repo" add -A && git -C "$repo" -c user.name=t -c user.email=t@example.invalid commit -qm "$1"; }
fixture; spec SPEC-001-thing.md accepted; (cd "$repo" && "$tool" >/dev/null); commit fresh
sed -i 's/^title: .*/title: "Renamed"/' "$repo/docs/specs/SPEC-001-thing.md"; commit "stale index"
(cd "$repo" && "$tool" >/dev/null); git -C "$repo" add -A
expect "staged fix: working tree passes"        0 "$tool" --check
expect "staged fix: pushed commit is stale"     1 env PRE_COMMIT_TO_REF=HEAD "$tool" --check
expect "staged fix: --ref is stale"             1 "$tool" --check --ref HEAD
git -C "$repo" reset -q --hard HEAD~1; git -C "$repo" branch -q other HEAD
git -C "$repo" switch -q other; sed -i 's/^title: .*/title: "Other"/' "$repo/docs/specs/SPEC-001-thing.md"; commit "stale on other"
git -C "$repo" switch -q main
expect "pushing a stale branch from a fresh one" 1 env PRE_COMMIT_TO_REF=other "$tool" --check
expect "pushing the fresh branch"               0 env PRE_COMMIT_TO_REF=main "$tool" --check
echo "uncommitted" >> "$repo/docs/specs/INDEX.md"
expect "dirty tree, fresh commit passes"        0 env PRE_COMMIT_TO_REF=HEAD "$tool" --check
expect "unresolvable ref"                       2 env PRE_COMMIT_TO_REF=nope "$tool" --check
expect "--ref without a value"                  2 "$tool" --check --ref
expect "--ref without --check"                  2 "$tool" --ref HEAD
git -C "$repo" checkout -q -- .; git -C "$repo" rm -q docs/specs/INDEX.md; commit "drop index"
expect "index missing in commit is stale"       1 "$tool" --check --ref HEAD
expect "rewrite ignores PRE_COMMIT_TO_REF"      0 env PRE_COMMIT_TO_REF=nope "$tool"

[ "$fails" -eq 0 ] || { echo "$fails test(s) failed"; exit 1; }
echo "all gen-index tests passed"
